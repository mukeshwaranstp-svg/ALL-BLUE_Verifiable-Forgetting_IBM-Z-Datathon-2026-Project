export function createCanonicalStages(progressStage: number, failedAt?: number, failureReason?: string): StageDetail[] {
  const STAGE_NAMES = [
    { num: 1, name: 'Database Purge', desc: 'Transactional Shard Zero-Trace Deletion' },
    { num: 2, name: 'Tombstone Registry', desc: 'Merkle Ledger Cryptographic Tombstone' },
    { num: 3, name: 'Backup WORM Scan', desc: 'Write-Once Read-Many Tape Snapshot Scrub' },
    { num: 4, name: 'Sandbox Verification', desc: 'Dynamic Isolated Dynamic Test Suite' },
    { num: 5, name: 'Feature Store Scrub', desc: 'FeatureStore v2.1 Embedding Invalidation' },
    { num: 6, name: 'Telum ML Unlearning', desc: 'Hardware-Accelerated DP-SGD Retraining' },
    { num: 7, name: 'ZKP Membership Proof', desc: 'Zero-Knowledge Groth16 Exclusion Proof' },
    { num: 8, name: 'Immutable Receipt Minting', desc: 'HSM z16 Crypto Express 8S Signing' },
  ];

  return STAGE_NAMES.map((s) => {
    let status: 'COMPLETED' | 'IN_PROGRESS' | 'PENDING' | 'FAILED' = 'PENDING';
    let detail = `Awaiting orchestrator trigger for ${s.name}`;

    if (failedAt === s.num) {
      status = 'FAILED';
      detail = failureReason || `Failed during execution of ${s.name}`;
    } else if (s.num < progressStage) {
      status = 'COMPLETED';
      detail = `Successfully verified and committed in IBM z16 Enclave.`;
    } else if (s.num === progressStage) {
      status = 'IN_PROGRESS';
      detail = `Actively processing inside Telum II accelerator array.`;
    }

    return {
      stageNumber: s.num as any,
      name: s.name,
      description: s.desc,
      status,
      latencyMs: s.num < progressStage ? Math.floor(120 + Math.random() * 450) : undefined,
      details: detail,
      error: failedAt === s.num ? failureReason : undefined,
    };
  });
}

