export function createTruthfulStages(progressStage: number, failedAt?: number, failureReason?: string): StageDetail[] {
  const STAGE_NAMES = [
    { num: 1, name: 'Database Purge', desc: 'Transactional Shard Deletion (Customer Rows Cleared)' },
    { num: 2, name: 'Tombstone Registry', desc: 'Cryptographic Tombstone Entry Appended' },
    { num: 3, name: 'Backup WORM Scan', desc: 'WORM Snapshot Cryptographic Key Reconciliation' },
    { num: 4, name: 'Sandbox Verification', desc: 'Dynamic Isolated Air-Gap Regression Tests' },
    { num: 5, name: 'Feature Store Scrub', desc: 'Feature Embedding Index Invalidation' },
    { num: 6, name: 'Model Retraining', desc: 'Target Retraining on Excluded Dataset' },
    { num: 7, name: 'Verification Audit', desc: 'Zero-Knowledge Witness & Membership Inference Verification' },
    { num: 8, name: 'Receipt Issuance', desc: 'Verifiable Deletion Certificate Generation' },
  ];

  return STAGE_NAMES.map((s) => {
    let status: 'COMPLETED' | 'IN_PROGRESS' | 'PENDING' | 'FAILED' = 'PENDING';
    let detail = `Awaiting orchestrator trigger for ${s.name}`;

    if (failedAt === s.num) {
      status = 'FAILED';
      detail = failureReason || `Failed during execution of ${s.name}`;
    } else if (s.num < progressStage) {
      status = 'COMPLETED';
      detail = `Completed and verified in testbed pipeline.`;
    } else if (s.num === progressStage) {
      status = 'IN_PROGRESS';
      detail = `Actively executing in pipeline runner.`;
    }

    return {
      stageNumber: s.num as any,
      name: s.name,
      description: s.desc,
      status,
      latencyMs: s.num < progressStage ? Math.floor(120 + Math.random() * 450) : undefined,
      details: detail,
      error: failedAt === s.num ? failureReason : undefined,
    };
  });
}

